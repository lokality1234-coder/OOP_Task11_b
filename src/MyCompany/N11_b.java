//пакеты позволяют ограничить классы логически в наборы, позволяет избежать ошибок между именами классов
package MyCompany;

//подключение типа (класса) для чтения данных с клавиатуры
import java.util.Scanner;

//подключение класса для обработки ошибки при неправильном вводе
import java.util.InputMismatchException;

//Обьявление класса, в Java всё находить внутри классов
//public - значит класс доступен извне, "N11_b" - имя класса,должна совпадать в именем файла
public class N11_b {

    //писать нужно именно в главном файле так как он вызываеться первым
    //Функция вывода справки по использованию программы
    static void printHelp(){
        System.out.println("  Справка:");
        System.out.println("  java N11_b                - ввод данных через консоль");
        System.out.println("  java N11_b <x> <y> <z>    - передача значений через аргументы");
        System.out.println("  java N11_b -h           - вывод этой справки");
        System.out.println("  java N11_b --help         - вывод этой справки");
    }

    //Главный метод, String[] args - массив строк, переданных при запуске программы
    public static void main(String[] args) {

        //проходим по всем аргументам командной строки
        for (String arg : args) {
            //если среди них есть -h или --help
            if (arg.equals("-h") || arg.equals("--help")) {
                printHelp(); //выводим справку
                return;//завершаем, можно return заменить на break и программа продолжиться
            }
        }

        //добавляем проверку assert из модуля
        //если модуль содержиться в том же пакете что и класс то его можно добавлять и использовать напрямую
        CustomMath.test_a();
        CustomMath.test_b();

        //Создание обьекта для ввода с клавиатуры
        Scanner in = new Scanner(System.in);

        //ОбЪект in, отвечает за чтение данных
        //.nextDouble() - специальный метод класса Scanner, который заставляет программу останавливаться,
        // ждать, пока пользователь не введет число и не нажмет Enter
        //затем преобразует ввод в тип double
        //try - пробуем выполнить код, в котором может возникнуть ошибка
        try {

            //объявляем переменные заранее, так как значения будут присваиваться в разных ветках if/else
            double x, y, z;

            //args.length - количество переданных аргументов
            //если передано ровно 3 аргумента, берём значения из них
            if (args.length == 3) {
                //Double.parseDouble() - преобразует строку в число типа double
                //args[0], args[1], args[2] - первый, второй и третий аргументы командной строки
                x = Double.parseDouble(args[0]);
                y = Double.parseDouble(args[1]);
                z = Double.parseDouble(args[2]);
            } else {
                //иначе вводим данные с клавиатуры
                //println - выводит значение и переводит курсор на новую строку
                System.out.println("Введите значения x, y, z:");
                x = in.nextDouble();
                y = in.nextDouble();
                z = in.nextDouble();
            }

            //локальные переменные типа double в которых инициализируются функции
            //можно подключать модули и использовать их функции если модуль содержиться в том же пакете что и класс
            double a = CustomMath.calc_a(x, y, z);
            double b = CustomMath.calc_b(x, y);

            //printf - форматированный вывод как в с
            System.out.printf("\nОтвет:\na = %.3f;\nb = %.3f\n", a, b);

            //catch - перехватывает ошибку
            //(InputMismatchException e) - если метод класса Scanner (nextDouble()) ожидает один тип а получает другой
            //NumberFormatException - если в аргументах командной строки передали не число (например, abc)
            //знак | позволяет перехватить сразу несколько типов ошибок одним блоком catch
        } catch (InputMismatchException | NumberFormatException e) {
            //вывод сообщения об ошибке
            System.out.println("Ошибка: необходимо вводить только числа.");
        }
    }

}//проверка ветки